// Generates docs/i18n-review.md for a native reviewer (spec v3 §5): every key with EN and EL, the glossary, the Greek
// metric labels, and a "needs native review" banner. `--check` exits 1 when the document is stale.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => JSON.parse(readFileSync(path.join(root, 'src/lib/i18n', f), 'utf8'));
const en = read('en.json');
const el = read('el.json');
const labelsSrc = readFileSync(path.join(root, 'src/lib/catalog/labels.ts'), 'utf8');

// the metric labels: expand the withPrefix(...) calls the same way labels.ts does (one named map per archetype)
const metricLabels = [];
const entries = (block) => [...block.matchAll(/^\s*(\w+): '([^']+)',?$/gm)].map((m) => [m[1], m[2]]);
const maps = {};
for (const m of labelsSrc.matchAll(/const ([A-Z_]+) = \{([\s\S]*?)\r?\n\};/g)) maps[m[1]] = m[2];
for (const m of labelsSrc.matchAll(/withPrefix\('(\w+)', ([A-Z_]+|\{[\s\S]*?\r?\n  \})\)/g)) {
  const prefix = m[1];
  const block = maps[m[2]] ?? m[2];
  for (const [k, v] of entries(block)) metricLabels.push([`${prefix}:${k}`, v]);
}
const dimensionLabels = entries(labelsSrc.match(/DIMENSION_LABELS_EL: Record<string, string> = \{([\s\S]*?)\r?\n\};/)?.[1] ?? '');

const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
const lines = [];
lines.push('# Greek translation review');
lines.push('');
lines.push('> **Needs native review.** The Greek column is a draft written with the glossary below; a native speaker should');
lines.push('> read every row before a Greek workspace goes live. Edit `src/lib/i18n/el.json` (UI strings) and');
lines.push('> `src/lib/catalog/labels.ts` (metric labels), then run `npm run i18n:review` to refresh this document.');
lines.push('');
lines.push('Generated by `scripts/i18n-review.mjs` from `src/lib/i18n/en.json`, `src/lib/i18n/el.json` and `src/lib/catalog/labels.ts`.');
lines.push(`${Object.keys(en).length} UI keys · ${metricLabels.length} metric labels · ${dimensionLabels.length} table dimensions.`);
lines.push('');
lines.push('## Glossary (fixed)');
lines.push('');
lines.push('| English | Greek |');
lines.push('|---|---|');
for (const [a, b] of [['report', 'αναφορά'], ['dashboard', 'πίνακας'], ['goal', 'στόχος'], ['automation', 'αυτοματισμός'], ['milestone', 'ορόσημο'], ['integration', 'σύνδεση'], ['campaign', 'καμπάνια'], ['conversions', 'μετατροπές'], ['spend', 'δαπάνη'], ['template', 'πρότυπο'], ['client', 'πελάτης'], ['period', 'περίοδος'], ['comparison', 'σύγκριση']]) lines.push(`| ${a} | ${b} |`);
lines.push('');
lines.push('## UI strings');
lines.push('');
let ns = '';
for (const k of Object.keys(en).sort()) {
  const area = k.slice(0, k.indexOf('.'));
  if (area !== ns) {
    ns = area;
    lines.push('');
    lines.push(`### ${ns}`);
    lines.push('');
    lines.push('| Key | English | Greek |');
    lines.push('|---|---|---|');
  }
  lines.push(`| \`${k}\` | ${esc(en[k])} | ${esc(el[k] ?? '')} |`);
}
lines.push('');
lines.push('## Metric labels (Greek pages)');
lines.push('');
lines.push('Only these keys get a Greek label; every other metric, chart or table keeps the platform\'s own English title.');
lines.push('');
lines.push('| Key | Greek |');
lines.push('|---|---|');
for (const [k, v] of metricLabels.sort((a, b) => a[0].localeCompare(b[0]))) lines.push(`| \`${k}\` | ${esc(v)} |`);
lines.push('');
lines.push('## "About these numbers" (per platform, Greek)');
lines.push('');
lines.push('| Platform | Part | Greek |');
lines.push('|---|---|---|');
{
  const notesSrc = readFileSync(path.join(root, 'src/lib/catalog/data-notes.ts'), 'utf8');
  const block = notesSrc.match(/DATA_NOTES_EL: Record<string, DataNote> = \{([\s\S]*?)\r?\n\};/)?.[1] ?? '';
  // shared sentences live in constants (ADS_TZ_EL, …): resolve them so the reviewer reads words, not names
  const consts = Object.fromEntries([...notesSrc.matchAll(/const (\w+_EL) = '([^']*)';/g)].map((m) => [m[1], m[2]]));
  const esc = (v) => String(consts[v] ?? v).replace(/\|/g, '\\|');
  let slug = '';
  for (const line of block.split(/\r?\n/)) {
    const s = line.match(/^\s{2}(\w+): \{/);
    if (s) slug = s[1];
    const inline = line.match(/^\s{2}(\w+): \{ (.*) \},?$/);
    if (inline) {
      slug = inline[1];
      for (const p of inline[2].matchAll(/(\w+): (?:'([^']*)'|(\w+))/g)) lines.push(`| \`${slug}\` | ${p[1]} | ${esc(p[2] ?? p[3])} |`);
      continue;
    }
    const part = line.match(/^\s{4}(\w+): (?:'([^']*)'|(\w+)),?$/);
    if (part && slug) lines.push(`| \`${slug}\` | ${part[1]} | ${esc(part[2] ?? part[3])} |`);
  }
}
lines.push('');
lines.push('## Table dimensions (first column)');
lines.push('');
lines.push('| Dimension | Greek |');
lines.push('|---|---|');
for (const [k, v] of dimensionLabels) lines.push(`| \`${k}\` | ${esc(v)} |`);
lines.push('');
lines.push('## Known gaps');
lines.push('');
lines.push('- The catalog descriptions, API docs, MCP, AI output and platform names stay English by design (spec v3 §5).');
lines.push('- Month and weekday names come from `Intl`; numbers follow the project\'s decimal setting.');
lines.push('- Content typed or chosen by the agency stays as typed: report titles, block titles, the default templates\' section');
lines.push('  names ("Paid media", "Social media", …), timeline events and analysis cards (AI output is not translated).');
lines.push('- The per-platform "About these numbers" sentences (`src/lib/catalog/data-notes.ts`) are catalog text and stay English;');
lines.push('  only the generic sentence on the client page is translated.');
lines.push('- The metric picker in the widget settings (MetricSelect) shows the catalog\'s English titles: its items carry no');
lines.push('  reference key, so the label map cannot be applied there.');
lines.push('- The per-integration setup help on the connect page (`HELP` in `src/app/projects/[id]/connect/[slug]/page.tsx`: where to');
lines.push('  find a token, env-var names, URL formats), the OAuth provider names and account nouns ("ad accounts", "properties"),');
lines.push('  the overview anomaly metric names ("Meta spend", "Sessions", "Google Ads spend") and the browser-tab page titles stay');
lines.push('  English (technical setup text and platform terms).');
lines.push('- The per-platform "About these numbers" sentences now have a Greek copy in `src/lib/catalog/data-notes.ts`');
lines.push('  (`DATA_NOTES_EL`, listed below for review).');
lines.push('');

const out = lines.join('\n') + '\n';
const target = path.join(root, 'docs/i18n-review.md');
if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== out) {
    console.error('i18n-review: docs/i18n-review.md is stale — run `npm run i18n:review`');
    process.exit(1);
  }
  console.log('i18n-review: up to date');
} else {
  writeFileSync(target, out);
  console.log(`i18n-review: wrote docs/i18n-review.md (${Object.keys(en).length} keys, ${metricLabels.length} labels)`);
}
