// Writes src/lib/geo/country-codes.ts: every ISO 3166-1 country as [alpha-2, alpha-3, numeric, English names…], from the
// i18n-iso-countries package (MIT). Run once when the list needs refreshing; the app never depends on the package:
//   cd E:\Claude\tmp\geo-build && npm i i18n-iso-countries
//   node scripts/build-country-codes.mjs --deps E:\Claude\tmp\geo-build\node_modules
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import path from 'node:path';

const i = process.argv.indexOf('--deps');
const deps = i > 0 ? process.argv[i + 1] : 'E:/Claude/tmp/geo-build/node_modules';
const require = createRequire(path.join(deps, 'noop.js'));
const countries = require('i18n-iso-countries');

const rows = Object.keys(countries.getAlpha2Codes())
  .sort()
  .map((a2) => {
    const names = [].concat(countries.getName(a2, 'en', { select: 'all' }) ?? []);
    return [a2, countries.alpha2ToAlpha3(a2), countries.alpha2ToNumeric(a2), ...names];
  });

const out = `// Generated by scripts/build-country-codes.mjs from i18n-iso-countries (MIT). Do not edit by hand.
// [alpha-2, alpha-3, ISO numeric, English names…]
export const COUNTRY_CODES: readonly (readonly string[])[] = ${JSON.stringify(rows)};
`;
writeFileSync(new URL('../src/lib/geo/country-codes.ts', import.meta.url), out);
console.log('countries', rows.length);
