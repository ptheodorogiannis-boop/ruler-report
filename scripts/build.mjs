// `npm run build`. With a SQLite DATABASE_URL (local, Docker) it builds exactly as before. With a Postgres DATABASE_URL
// (Vercel with a Neon database) it writes prisma/postgres/schema.prisma from the SQLite schema, generates the client for
// it, applies the schema to the database (refusing changes that would drop data), seeds the demo data when SEED_DEMO=1,
// then builds. On Vercel it stops early with a readable message when the database or APP_SECRET is missing.
// See docs/DEPLOY-VERCEL.md.
import { spawnSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const require_ = createRequire(import.meta.url);

export const PG_SCHEMA = 'prisma/postgres/schema.prisma';
const isPostgres = (url = '') => /^postgres(ql)?:\/\//i.test(url);

/** The steps `npm run build` runs for this environment; throws when the environment cannot work. */
export function buildPlan(env) {
  const pg = isPostgres(env.DATABASE_URL);
  if (env.VERCEL && !pg)
    throw new Error('On Vercel, DATABASE_URL must point to a Postgres database: add a Neon database from the project\'s Storage tab and connect it to this environment (docs/DEPLOY-VERCEL.md).');
  if (!pg) return ['prisma generate', 'next build'];
  if (!env.APP_SECRET || env.APP_SECRET.length < 32)
    throw new Error('APP_SECRET must be set to 32 or more random characters: it signs sessions and encrypts integration credentials (docs/DEPLOY-VERCEL.md).');
  return [
    `write ${PG_SCHEMA}`,
    `prisma generate --schema ${PG_SCHEMA}`,
    `prisma db push --skip-generate --schema ${PG_SCHEMA}`,
    ...(env.SEED_DEMO === '1' ? ['tsx prisma/seed.ts'] : []),
    'next build',
  ];
}

/** The SQLite schema with the Postgres provider; the direct (unpooled) connection is used for schema changes when set. */
export function pgSchema(src, env) {
  let out = src.replace(/provider\s*=\s*"sqlite"/, 'provider = "postgresql"');
  if (env.DATABASE_URL_UNPOOLED) out = out.replace(/(url\s*=\s*env\("DATABASE_URL"\))/, '$1\n  directUrl = env("DATABASE_URL_UNPOOLED")');
  return `// Generated by scripts/build.mjs from prisma/schema.prisma; do not edit.\n${out}`;
}

function main() {
  // the same .env files Next.js reads, so a local Postgres URL in .env picks the Postgres path too
  const { loadEnvConfig } = require_('@next/env');
  loadEnvConfig(process.cwd());
  let plan;
  try {
    plan = buildPlan(process.env);
  } catch (e) {
    console.error(`\nBuild stopped: ${e.message}\n`);
    process.exit(1);
  }
  for (const step of plan) {
    console.log(`\n> ${step}`);
    if (step.startsWith('write ')) {
      mkdirSync(path.dirname(PG_SCHEMA), { recursive: true });
      writeFileSync(PG_SCHEMA, pgSchema(readFileSync('prisma/schema.prisma', 'utf8'), process.env));
      continue;
    }
    const r = spawnSync(`npx ${step}`, { stdio: 'inherit', shell: true, env: process.env });
    if (r.status !== 0) process.exit(r.status ?? 1);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) main();
